//! Распознавание и перепечатка системным шрифтом выглядят хуже этой картинки,
//! поэтому буквы со скана не собираются заново. Рисунок листа остаётся как в файле.

/// Ничего не меняет. Оставлено, чтобы вызов со страницы был явным:
/// скан без текстовых команд так и хранится одной картинкой.
pub fn maybe_scan(elements: &mut Vec<crate::Element>, page_w: f32, page_h: f32) {
    let _ = (elements, page_w, page_h);
}
